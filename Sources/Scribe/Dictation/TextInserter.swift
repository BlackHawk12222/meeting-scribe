// TextInserter.swift
// Types the dictated text into whatever app you're using.
//
// The trick every dictation app uses (Handy, Wispr Flow, SuperWhisper…):
//  1. Save what's on your clipboard.
//  2. Put the text on the clipboard.
//  3. Pretend to press ⌘V (a "synthetic" key event made with CGEvent).
//  4. Put your old clipboard back.
// Pasting works in almost every app and is instant even for long text, while
// "typing" letter by letter is slow and breaks with autocomplete.
//
// Step 3 needs Accessibility permission. Without it, we stop after step 2 and
// tell you to press ⌘V yourself.
//
// 0.3: first we try to put the text straight into the focused text field via Accessibility
// (no clipboard at all) and check that it landed; the clipboard path is the fallback.

import AppKit
import ApplicationServices
import Carbon.HIToolbox

@MainActor
enum TextInserter {
    enum Outcome { case typedDirectly, pasted, copiedOnly }

    /// Whether to try typing straight into the text field (no clipboard) first. Settings key "directInsert".
    static var directInsert: Bool { UserDefaults.standard.object(forKey: "directInsert") as? Bool ?? true }

    static func insert(_ text: String, restoreClipboard: Bool) async -> Outcome {
        // 0) Best: put the text straight into the focused text field through Accessibility
        //    (no clipboard, so there's nothing to race). Only counts if we can SEE it worked.
        if directInsert, Permissions.accessibilityGranted, insertViaAccessibility(text) {
            return .typedDirectly
        }
        return await paste(text, restoreClipboard: restoreClipboard)
    }

    // MARK: Clipboard + ⌘V

    /// v0.2 bug ("it pasted my PREVIOUS dictation"): the old clipboard was put back 350 ms after
    /// ⌘V. Some apps read the clipboard later than that, so they got the restored clipboard —
    /// which, after an earlier dictation, was that earlier text. Now:
    ///  • the new text is written and we CHECK the pasteboard really holds it (changeCount moved
    ///    and the string matches) before pressing ⌘V;
    ///  • the old clipboard comes back only after 600 ms, and only if nothing else touched it.
    static func paste(_ text: String, restoreClipboard: Bool) async -> Outcome {
        let pb = NSPasteboard.general
        let saved = snapshot(pb)
        guard write(text, to: pb) else { return .copiedOnly }
        let ourChange = pb.changeCount

        guard Permissions.accessibilityGranted else { return .copiedOnly }

        // Wait until you've let go of ⌘/⌥/⌃/⇧, or our ⌘V would turn into e.g. ⌘⌥V.
        for _ in 0..<20 where !NSEvent.modifierFlags.intersection([.command, .option, .control, .shift]).isEmpty {
            try? await Task.sleep(nanoseconds: 30_000_000)
        }
        try? await Task.sleep(nanoseconds: 40_000_000)   // let the pasteboard server publish it
        // Still ours? (A clipboard manager or another app may have written in between.)
        if pb.changeCount != ourChange || pb.string(forType: .string) != text {
            guard write(text, to: pb) else { return .copiedOnly }
        }
        let pastedChange = pb.changeCount
        pressCommandV()

        if restoreClipboard {
            let restore = saved
            Task { @MainActor in
                try? await Task.sleep(nanoseconds: 600_000_000)
                if pb.changeCount == pastedChange {
                    pb.clearContents()
                    if !restore.isEmpty { pb.writeObjects(restore) }
                }
            }
        }
        return .pasted
    }

    /// Copy every item, every format (text, images, files…) so it can be put back.
    static func snapshot(_ pb: NSPasteboard) -> [NSPasteboardItem] {
        (pb.pasteboardItems ?? []).map { item in
            let copy = NSPasteboardItem()
            for type in item.types {
                if let data = item.data(forType: type) { copy.setData(data, forType: type) }
            }
            return copy
        }
    }

    /// Put `text` on the pasteboard and confirm it's really there. The two marker types ask
    /// clipboard-history apps (Raycast, Paste, Maccy…) not to save this temporary copy.
    @discardableResult
    static func write(_ text: String, to pb: NSPasteboard) -> Bool {
        let before = pb.changeCount
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pb.writeObjects([item])
        return pb.changeCount != before && pb.string(forType: .string) == text
    }

    // MARK: Accessibility (direct)

    /// Apps whose text fields say "OK" to an Accessibility insert but ignore it, or handle it
    /// badly (browsers, Electron apps, terminals). They always get the ⌘V path.
    static let pasteOnlyApps: Set<String> = [
        "com.google.Chrome", "com.brave.Browser", "com.microsoft.edgemac", "org.mozilla.firefox",
        "com.apple.Safari", "company.thebrowser.Browser", "com.tinyspeck.slackmacgap", "com.hnc.Discord",
        "com.microsoft.VSCode", "com.todesktop.230313mzl4w4u92", "notion.id", "com.figma.Desktop",
        "com.apple.Terminal", "com.googlecode.iterm2", "dev.warp.Warp-Stable", "com.microsoft.teams2",
        "com.openai.chat", "md.obsidian", "com.spotify.client",
    ]

    /// Replace the selection (or insert at the cursor) in the focused text field. Returns true
    /// only if the field's value afterwards actually contains the new text.
    static func insertViaAccessibility(_ text: String) -> Bool {
        guard let app = NSWorkspace.shared.frontmostApplication,
              let bundle = app.bundleIdentifier, !pasteOnlyApps.contains(bundle),
              app.processIdentifier != ProcessInfo.processInfo.processIdentifier else { return false }
        let axApp = AXUIElementCreateApplication(app.processIdentifier)
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(axApp, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let f = focused, CFGetTypeID(f) == AXUIElementGetTypeID() else { return false }
        let element = f as! AXUIElement
        var role: CFTypeRef?
        AXUIElementCopyAttributeValue(element, kAXRoleAttribute as CFString, &role)
        let r = role as? String ?? ""
        guard r == kAXTextFieldRole as String || r == kAXTextAreaRole as String || r == "AXComboBox" else { return false }
        var settable = DarwinBoolean(false)
        guard AXUIElementIsAttributeSettable(element, kAXSelectedTextAttribute as CFString, &settable) == .success,
              settable.boolValue else { return false }
        func value() -> String? {
            var v: CFTypeRef?
            guard AXUIElementCopyAttributeValue(element, kAXValueAttribute as CFString, &v) == .success else { return nil }
            return v as? String
        }
        guard let before = value(), before.count < 200_000 else { return false }   // huge docs: just paste
        guard AXUIElementSetAttributeValue(element, kAXSelectedTextAttribute as CFString, text as CFString) == .success,
              let after = value() else { return false }
        return after != before && after.contains(text)
    }
    /// Synthetic ⌘V. Key code 9 is the "V" key position on a US (QWERTY) keyboard.
    static func pressCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let v = CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }
}
