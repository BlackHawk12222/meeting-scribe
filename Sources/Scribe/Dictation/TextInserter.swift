// TextInserter.swift
// Types the dictated text into whatever app you're using.
//
// The trick every dictation app uses (Handy, Wispr Flow, SuperWhisper…):
//  1. Save what's on your clipboard.
//  2. Put the text on the clipboard.
//  3. Pretend to press ⌘V (a "synthetic" key event made with CGEvent).
//  4. Put your old clipboard back.
// Pasting works in almost every app and is instant even for long text, while
// "typing" letter by letter is slow and breaks with autocomplete.
//
// Step 3 needs Accessibility permission. Without it, we stop after step 2 and
// tell you to press ⌘V yourself.

import AppKit
import Carbon.HIToolbox

@MainActor
enum TextInserter {
    enum Outcome { case pasted, copiedOnly }

    static func insert(_ text: String, restoreClipboard: Bool) async -> Outcome {
        let pb = NSPasteboard.general

        // 1) Save the current clipboard (every item, every format: text, images, files…).
        let saved: [NSPasteboardItem] = (pb.pasteboardItems ?? []).map { item in
            let copy = NSPasteboardItem()
            for type in item.types {
                if let data = item.data(forType: type) { copy.setData(data, forType: type) }
            }
            return copy
        }

        // 2) Put our text on it. The two marker types ask clipboard-history apps
        //    (Raycast, Paste, Maccy…) not to save this temporary copy.
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pb.writeObjects([item])
        let ourChange = pb.changeCount

        guard Permissions.accessibilityGranted else { return .copiedOnly }

        // Wait until you've let go of ⌘/⌥/⌃/⇧, or our ⌘V would turn into e.g. ⌘⌥V.
        for _ in 0..<20 where !NSEvent.modifierFlags.intersection([.command, .option, .control, .shift]).isEmpty {
            try? await Task.sleep(nanoseconds: 50_000_000)
        }
        try? await Task.sleep(nanoseconds: 60_000_000)   // let the clipboard settle (Handy uses 60 ms too)

        // 3) Press and release ⌘V.
        pressCommandV()

        // 4) Give the app time to read the clipboard, then restore the old one —
        //    but only if nothing else changed the clipboard in the meantime.
        if restoreClipboard {
            try? await Task.sleep(nanoseconds: 350_000_000)
            if pb.changeCount == ourChange {
                pb.clearContents()
                if !saved.isEmpty { pb.writeObjects(saved) }
            }
        }
        return .pasted
    }

    /// Synthetic ⌘V. Key code 9 is the "V" key position on a US (QWERTY) keyboard.
    static func pressCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let v = CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: v, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }
}
