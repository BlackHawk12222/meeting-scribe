#!/usr/bin/env python3
# 0.7.6: builds Sources/Scribe/Engine/CommonWords.swift, the "everyday English" stoplist that
# "Boost my words" and learned fix-ups use so they never change a common word on their own.
#
# Source: word counts from 35 public-domain Project Gutenberg books (novels and essays), keeping
# words that are mostly written lowercase (so character names drop out), the top 5,000 by count,
# plus a short hand-picked list of everyday modern words the old books lack (email, app, meeting…).
# Usage: python3 scripts/make_common_words.py   (downloads the books from a Gutenberg mirror)
import collections, re, urllib.request, pathlib

BOOKS = [1342, 1661, 2701, 74, 11, 84, 345, 1400, 76, 514, 98, 1260, 158, 174, 2554, 1952, 5200, 46, 16,
         120, 35, 36, 1184, 219, 244, 55, 113, 1080, 4300, 2600, 768, 1232, 6130, 3207, 2814]
MIRROR = "https://gutenberg.pglaf.org/cache/epub/{0}/pg{0}.txt"
MODERN = """ok okay yeah yep nope hey hi bye email emails phone phones online website web app apps computer
computers internet video videos photo photos text texts message messages meeting meetings call calls team
teams project projects school class classes homework teacher teachers student students test tests quiz game
games play played player players movie movies music song songs check checked update updates file files folder
folders download upload link links click type typed button screen screens mouse keyboard laptop tablet code
coding program programs data offline password login account accounts sign signed setting settings feature
features design designs build builds bug bugs fix fixed fixes print printer printed robot robots robotics
practice practise competition tournament field drive driver drivers driving car cars truck bus bike ride rides
riding rode right rights write writes wrote written rite night light might sight fight kite site white bite
quite mat cat sat hat bat rat fat pat vat chat that flat sound loud cloud kind mind find wind lunch dinner
breakfast pizza burger coffee tea snack weekend monday tuesday wednesday thursday friday saturday sunday
january february march april may june july august september october november december today tomorrow
yesterday tonight morning afternoon evening alright sure thanks thank please sorry cool awesome great nice
fun busy ready done start started stop stopped finish finished plan plans idea ideas notes note list lists
slide slides doc docs sheet sheets chart charts table tables number numbers percent dollar dollars cost price
prices store shop shopping order ordered cart pay paid card cards bank money job jobs work worked working boss
manager office desk church youth group friend friends mom dad brother sister family kid kids baby dog dogs
cat cats horse horses""".split()

low, cap = collections.Counter(), collections.Counter()
for b in BOOKS:
    t = urllib.request.urlopen(MIRROR.format(b)).read().decode("utf-8", "ignore")
    a, e = t.find("*** START"), t.find("*** END")
    if a >= 0: t = t[t.find("\n", a):]
    if e >= 0: t = t[:e]
    for w in re.findall(r"[A-Za-z]+(?:'[a-z]+)?", t):
        (cap if w[0].isupper() else low)[w.lower()] += 1
total = collections.Counter()
for w, c in low.items():
    if "'" in w or (len(w) == 1 and w not in ("a", "i")): continue
    if c >= 2 * cap.get(w, 0) or c > 200: total[w] = c + cap.get(w, 0)
words = [w for w, _ in total.most_common(5000)]
words += [w for w in MODERN if w not in words]
out = pathlib.Path(__file__).resolve().parent.parent / "Sources/Scribe/Engine/CommonWords.swift"
lines = [" ".join(words[i:i + 24]) for i in range(0, len(words), 24)]
body = "\n".join("        " + l for l in lines)
TEMPLATE = """// CommonWords.swift — GENERATED by scripts/make_common_words.py. Do not edit by hand.
// 0.7.6: @N@ everyday English words (lowercase). "Boost my words" never replaces one of these on its
// own, and a learned fix-up that would change one needs your approval first. Built from word counts
// of 35 public-domain Project Gutenberg books plus a short list of everyday modern words.

import Foundation

enum CommonWords {
    static let count = @N@
    static let all: Set<String> = Set(list.split(whereSeparator: { $0 == " " || $0 == "\\n" }).map(String.init))
    static func contains(_ word: String) -> Bool { all.contains(word.lowercased()) }

    private static let list = \"\"\"
@BODY@
        \"\"\"
}
"""
out.write_text(TEMPLATE.replace("@N@", str(len(words))).replace("@BODY@", body))
print(len(words), "words ->", out)
